// ─── Tests ────────────────────────────────────────────────────────────────────

// Fork (Wnt/webmail), owner decision 2026-10-20: sending a reply no longer
// makes its recipients trusted senders (upstream added every To and Cc to the
// trusted-sender list or book, so their remote content loaded from then on).
// Trust comes only from the user's own "Always trust this sender" or Settings.

const REPLY = {
  to: 'Ann Example <ann@example.test>, bob@example.test',
  cc: 'carol@example.test',
  bcc: '',
  subject: 'Re: Lunch',
  body: '<p>Sounds good</p>',
  showCc: true,
  showBcc: false,
  selectedIdentityId: 'id-me',
  subAddressTag: '',
  mode: 'reply' as const,
  draftId: null,
};

const sendButton = () => screen.getAllByTestId('composer-send')[0] as HTMLButtonElement;

describe('sending a reply', () => {
  beforeEach(() => {
    addTrustedSenderSpy.mockClear();
    addToBookSpy.mockClear();
  });

  it.each(['reply', 'replyAll'] as const)('(%s) adds none of its recipients to the trusted senders', async (mode) => {
    const onSend = vi.fn(async () => {});
    render(
      <EmailComposer
        mode={mode}
        initialData={{ ...REPLY, mode }}
        replyTo={{ from: [{ email: 'ann@example.test', name: 'Ann Example' }], subject: 'Lunch', body: 'Lunch?' }}
        onSend={onSend}
      />,
    );
    fireEvent.click(sendButton());
    await act(() => new Promise((r) => setTimeout(r, 50)));
    expect(onSend).toHaveBeenCalled();
    expect(addTrustedSenderSpy).not.toHaveBeenCalled();
    expect(addToBookSpy).not.toHaveBeenCalled();
  });
});
