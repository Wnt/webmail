import { Editor } from '@tiptap/core';
import Document from '@tiptap/extension-document';
import Paragraph from '@tiptap/extension-paragraph';
import Text from '@tiptap/extension-text';
import { QuotedHtml } from '../quoted-html';
import { shouldBlockExternalFor } from '@/lib/email-content-cache';

it.each(['reply', 'forward'] as const)('failed-auth trusted From stays blocked in %s quote', mode => {
  const original = {
    from: [{ email: 'letters@trusted-sender.test' }],
    authenticationResults: { dmarc: { result: 'fail' as const } },
    subject: 'Forged message', receivedAt: '2026-01-01T00:00:00Z',
    htmlBody: '<p>Original</p><img src="https://images.example.test/track.png">',
  };
  expect(shouldBlockExternalFor(original, {
    externalContentPolicy: 'ask', allowExternalContent: false,
    isSenderTrusted: () => true, trustedSendersAddressBook: false, isTrustedAddressBookSender: () => false,
  })).toBe(true);
  render(<EmailComposer mode={mode} replyTo={original} />);
  const content = screen.getByTestId('rich-text-editor').getAttribute('data-content')!;
  expect(content).toContain('data-quoted-html');
  const editor = new Editor({ extensions: [Document, Paragraph, Text, QuotedHtml], content });
  try {
    const host = editor.view.dom.querySelector('.quoted-html-island') as HTMLElement;
    expect(host.shadowRoot!.querySelector('img')?.getAttribute('src')).not.toBe('https://images.example.test/track.png');
  } finally { editor.destroy(); }
});
