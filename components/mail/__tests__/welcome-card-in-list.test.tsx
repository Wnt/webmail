describe('welcome card on the phone', () => {
  it('is the message list header, not a fixed block above the list', () => {
    render(<MailApp />);
    const card = screen.getByText('welcome card');
    expect(screen.getByTestId('list-scroller')).toContainElement(card);
    expect(screen.getAllByText('welcome card')).toHaveLength(1);
  });
});
